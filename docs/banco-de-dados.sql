-- Referência do esquema (PostgreSQL / Supabase).
-- Em desenvolvimento o Hibernate cria e atualiza as tabelas (spring.jpa.hibernate.ddl-auto=update);
-- este script serve para documentação ou para criar o esquema manualmente no SQL Editor do Supabase.

create table clientes (
    id          bigint generated by default as identity primary key,
    rg          varchar(20)  not null,
    cpf         varchar(11)  not null unique,
    nome        varchar(255) not null,
    endereco    varchar(255) not null,
    profissao   varchar(255) not null
);

create table empregadores (
    id          bigint generated by default as identity primary key,
    cliente_id  bigint        not null references clientes(id),
    entidade    varchar(255)  not null,
    rendimento  numeric(12,2) not null
);

create table usuarios (
    id          bigint generated by default as identity primary key,
    username    varchar(60)  not null unique,
    senha_hash  varchar(255) not null,
    perfil      varchar(30)  not null check (perfil in ('CLIENTE','AGENTE_EMPRESA','AGENTE_BANCO')),
    cliente_id  bigint references clientes(id)
);

create table automoveis (
    id                bigint generated by default as identity primary key,
    matricula         varchar(30)   not null unique,
    ano               integer       not null,
    marca             varchar(60)   not null,
    modelo            varchar(60)   not null,
    placa             varchar(10)   not null unique,
    valor_diaria      numeric(10,2) not null,
    tipo_proprietario varchar(20)   not null check (tipo_proprietario in ('CLIENTE','EMPRESA','BANCO'))
);

create table contratos_credito (
    id                 bigint generated by default as identity primary key,
    banco_id           bigint        not null references usuarios(id),
    valor              numeric(12,2) not null,
    taxa_juros_mensal  numeric(6,3)  not null,
    parcelas           integer       not null
);

create table pedidos_aluguel (
    id                     bigint generated by default as identity primary key,
    cliente_id             bigint      not null references clientes(id),
    automovel_id           bigint      not null references automoveis(id),
    data_inicio            date        not null,
    data_fim               date        not null,
    status                 varchar(30) not null,
    parecer                varchar(1000),
    propriedade_registrada varchar(20),
    contrato_credito_id    bigint references contratos_credito(id),
    criado_em              timestamptz not null,
    atualizado_em          timestamptz not null
);
